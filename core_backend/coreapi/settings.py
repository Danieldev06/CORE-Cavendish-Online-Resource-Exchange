# Load environment variables from a local .env file if present.
def _load_env_file(env_path: Path) -> None:
    print(f"DEBUG: Loading .env from {env_path}")
    if not env_path.exists():
        print(f"DEBUG: .env file does not exist at {env_path}")
        return
    print(f"DEBUG: .env file exists at {env_path}")
    content = env_path.read_text(encoding='utf-8')
    print(f"DEBUG: .env content: {content[:200]}...")
    for line in content.splitlines():
        line = line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        key, value = line.split('=', 1)
        # Use direct assignment to override any existing environment variables
        os.environ[key.strip()] = value.strip().strip('"').strip("'")
        val = value.strip().strip('"').strip("'")
        print(f"DEBUG: Set {key.strip()} = {val[:20]}...")

